-- Drop tables in reverse dependency order (safe re-run)
BEGIN
  FOR t IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN (
      'INCIDENT_TICKET','NETWORK_ALARM','PROVISIONING_LOG','USAGE_RECORD',
      'BILLING_CHARGE','BILLING_INVOICE','BILLING_ACCOUNT','ORDER_FALLOUT',
      'ORDER_LINE_ITEM','ORDER_HEADER','SERVICE_SUBSCRIPTION',
      'PRODUCT_DEPENDENCY','PRODUCT_CATALOG','CUSTOMER_ADDRESS','CUSTOMER'
    )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

-- ============================================================
-- 1. CUSTOMER
-- ============================================================
CREATE TABLE CUSTOMER (
  CUSTOMER_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  FIRST_NAME       VARCHAR2(100)  NOT NULL,
  LAST_NAME        VARCHAR2(100)  NOT NULL,
  EMAIL            VARCHAR2(255)  NOT NULL UNIQUE,
  PHONE            VARCHAR2(20),
  DATE_OF_BIRTH    DATE,
  ACCOUNT_TYPE     VARCHAR2(20)   DEFAULT 'POSTPAID'
                   CHECK (ACCOUNT_TYPE IN ('POSTPAID','PREPAID','ENTERPRISE')),
  STATUS           VARCHAR2(20)   DEFAULT 'ACTIVE'
                   CHECK (STATUS IN ('ACTIVE','SUSPENDED','TERMINATED','PENDING')),
  CREDIT_SCORE     NUMBER(3),
  SEGMENT          VARCHAR2(50),
  CREATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_CUSTOMER_EMAIL  ON CUSTOMER(EMAIL);
CREATE INDEX IDX_CUSTOMER_STATUS ON CUSTOMER(STATUS);

-- ============================================================
-- 2. CUSTOMER_ADDRESS
-- ============================================================
CREATE TABLE CUSTOMER_ADDRESS (
  ADDRESS_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CUSTOMER_ID      NUMBER         NOT NULL,
  ADDRESS_TYPE     VARCHAR2(20)   DEFAULT 'BILLING'
                   CHECK (ADDRESS_TYPE IN ('BILLING','SERVICE','SHIPPING')),
  STREET_LINE1     VARCHAR2(255)  NOT NULL,
  STREET_LINE2     VARCHAR2(255),
  CITY             VARCHAR2(100)  NOT NULL,
  STATE            VARCHAR2(50)   NOT NULL,
  ZIP_CODE         VARCHAR2(20)   NOT NULL,
  COUNTRY          VARCHAR2(50)   DEFAULT 'USA',
  IS_PRIMARY       NUMBER(1)      DEFAULT 1 CHECK (IS_PRIMARY IN (0,1)),
  CREATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_ADDR_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
    REFERENCES CUSTOMER(CUSTOMER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_ADDR_CUSTOMER ON CUSTOMER_ADDRESS(CUSTOMER_ID);

-- ============================================================
-- 3. PRODUCT_CATALOG
-- ============================================================
CREATE TABLE PRODUCT_CATALOG (
  PRODUCT_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PRODUCT_CODE     VARCHAR2(50)   NOT NULL UNIQUE,
  PRODUCT_NAME     VARCHAR2(200)  NOT NULL,
  PRODUCT_TYPE     VARCHAR2(50)
                   CHECK (PRODUCT_TYPE IN ('VOICE','DATA','SMS','BUNDLE','ADDON','DEVICE','IOT')),
  CATEGORY         VARCHAR2(50)
                   CHECK (CATEGORY IN ('CONSUMER','ENTERPRISE','WHOLESALE')),
  MONTHLY_PRICE    NUMBER(10,2)   DEFAULT 0,
  SETUP_FEE        NUMBER(10,2)   DEFAULT 0,
  BILLING_CYCLE    VARCHAR2(20)   DEFAULT 'MONTHLY'
                   CHECK (BILLING_CYCLE IN ('MONTHLY','ANNUAL','ONE_TIME','USAGE')),
  STATUS           VARCHAR2(20)   DEFAULT 'ACTIVE'
                   CHECK (STATUS IN ('ACTIVE','DEPRECATED','DRAFT')),
  DESCRIPTION      CLOB,
  CREATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_PRODUCT_TYPE   ON PRODUCT_CATALOG(PRODUCT_TYPE);
CREATE INDEX IDX_PRODUCT_STATUS ON PRODUCT_CATALOG(STATUS);

